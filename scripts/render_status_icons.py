"""Generate Java geometry and a design sheet from the regularized status SVGs."""
from pathlib import Path
import html
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / 'app/src/main/assets/icons/ios-reference'
JAVA = ROOT / 'app/src/main/java/io/github/baishangui/thunder/IosIconAssets.java'
OUTPUT = ROOT / 'docs/status-icons-ios.svg'
ICONS = dict.fromkeys(['BLUETOOTH', 'SILENT', 'VIBRATE', 'NFC', 'ALARM', 'MOON', 'HOTSPOT', 'ROTATION', 'HEADPHONES', 'PERFORMANCE', 'AIRPLANE', 'LOCATION', 'WIFI', 'CELLULAR', 'VPN', 'BATTERY'])
LABELS = [('BLUETOOTH', '蓝牙'), ('SILENT', '静音'), ('VIBRATE', '振动'), ('NFC', 'NFC'), ('PERFORMANCE', '高性能'), ('ALARM', '闹钟'), ('MOON', '勿扰'),
          ('VPN', 'VPN'), ('HOTSPOT', '个人热点'), ('ROTATION', '旋转锁定'),
          ('HEADPHONES', '耳机'), ('AIRPLANE', '飞行模式'), ('LOCATION', '定位')]


def paths(kind):
    file = ASSETS / (kind.lower() + '.svg')
    if not file.exists(): return []
    root = ET.parse(file).getroot()
    assert root.attrib['viewBox'] == '0 0 24 24'
    return [(node.attrib['d'], float(node.attrib.get('stroke-width', 0)), 1, 0, 0, True) for node in root if node.tag.endswith('path')]


def generate_java():
    lines = ['package io.github.baishangui.thunder;', '',
             '/** Generated by scripts/render_status_icons.py from regularized status SVGs. Do not hand edit. */',
             'final class IosIconAssets {', '    static IosStatusIcons.Stroke[] paths(IosStatusIcons.Kind kind) {',
             '        return switch(kind) {']
    for kind in ICONS:
        lines.append(f'            case {kind} -> new IosStatusIcons.Stroke[] {{')
        for data, width, scale, x, y, even_odd in paths(kind):
            lines.append(f'                new IosStatusIcons.Stroke({json.dumps(data)}, {width}f, {scale}f, {x}f, {y}f, {str(even_odd).lower()}),')
        lines.append('            };')
    lines += ['            default -> new IosStatusIcons.Stroke[0];', '        };', '    }', '    static IosStatusIcons.Stroke[] stacked(int row) {', '        return switch(row) {']
    for row in [1,2]:
        lines.append(f'            case {row} -> new IosStatusIcons.Stroke[] {{')
        for data, width, scale, x, y, even_odd in paths('stacked_'+str(row)):
            lines.append(f'                new IosStatusIcons.Stroke({json.dumps(data)}, 0f, 1f, 0f, 0f, true),')
        lines.append('            };')
    lines += ['            default -> new IosStatusIcons.Stroke[0];', '        };', '    }', '    private IosIconAssets() { }', '}']
    JAVA.write_text('\n'.join(lines) + '\n')


def symbol(kind, level=4):
    parts = []
    for index, (data, width, scale, x, y, even_odd) in enumerate(paths(kind)):
        opacity = 1
        if kind == 'WIFI':
            opacity = 1 if (level > 0 if index == 0 else level * 3 / 4 >= index + .5) else .24
        if kind == 'CELLULAR':
            opacity = 1 if level >= 4-index else .24
        style = 'fill="currentColor"' if not width else f'fill="none" stroke="currentColor" stroke-width="{width/scale}" stroke-linecap="round" stroke-linejoin="round"'
        rule = 'fill-rule="evenodd"' if even_odd else ''
        parts.append(f'<path transform="translate({x} {y}) scale({scale})" d="{html.escape(data)}" {style} {rule} opacity="{opacity}"/>')
    content = ''.join(parts)
    return content


def stacked_signal(primary=3, secondary=2):
    parts=[]
    for row,level in [(1,primary),(2,secondary)]:
        for index,(data,*_) in enumerate(paths('stacked_'+str(row))):
            opacity=1 if level>=index+1 else .24
            parts.append(f'<path d="{data}" fill="currentColor" opacity="{opacity}"/>')
    return ''.join(parts)


def battery(level=75, charging=False, name='battery', dark=False):
    ink = '#17191d' if dark or charging else '#fff'
    font_size = (9.4 if level == 100 else 10.6) if charging else (11.2 if level == 100 else 12)
    center = 10.6 if charging else 12.25
    shape_paths=paths('BATTERY')
    body=''.join(f'<path d="{data}" fill="currentColor" opacity="{1 if index==0 else .5}"/>' for index,(data,*_) in enumerate(shape_paths))
    body+=f'<text x="{center}" y="{12 + font_size * .355}" text-anchor="middle" font-family="Arial,sans-serif" font-size="{font_size}" font-weight="700" fill="{ink}">{level}</text>'
    if charging:
        body += f'<g transform="translate(19.4 8.3) scale(.18 .31)" color="{ink}">' + symbol('PERFORMANCE') + '</g>'
    return body


